"""Write results/synth_core.md from a Yosys run of flow/synth/Makefile.

Usage: report.py <yosys output dir> <report.md> <state_inventory.md>
Reads stat.json, stat_cmos.txt and netlist.json, and the register declarations of src/*.v,
then reconciles the flip-flops after synthesis with the declared register bits.
"""
import datetime
import json
import re
import sys
from collections import Counter
from pathlib import Path

out, report, inventory = (Path(a) for a in sys.argv[1:4])
rtl = report.resolve().parents[1] / "src"
stat = json.loads((out / "stat.json").read_text())
net = json.loads((out / "netlist.json").read_text())
cmos = (out / "stat_cmos.txt").read_text()
version = stat["creator"].split(" (")[0]
modules = ["ab_filters", "ab_decide", "ab_core", "tt_um_orcunyilmaz06_approxbeat"]
core = modules[:3]                                 # the detector: what ab_state_inventory counts
files = {"tt_um_orcunyilmaz06_approxbeat": "project.v"}   # source of each module; default <module>.v


def base(name):
    """Module name without Yosys' parameter suffix: $paramod...\\ab_decide\\SQ_BITS=... -> ab_decide."""
    name = name.lstrip("\\")
    return name.split("\\")[1] if name.startswith("$paramod") else name


nets = {base(k): v for k, v in net["modules"].items()}
stats = {base(k): v for k, v in stat["modules"].items()}

# declared registers per module: names from src/<module>.v (function locals excluded),
# widths from the netlist, which keeps every named register at its declared width
DECL = re.compile(r"\b(?:output\s+)?reg\b(?:\s+signed)?(?:\s*\[[^\]]+\])?\s+"
                  r"([A-Za-z_]\w*(?:[ \t]*,[ \t]*[A-Za-z_]\w*)*)")   # names on one line only
declared = {}
for m in modules:
    src = (rtl / files.get(m, f"{m}.v")).read_text()
    text = re.sub(r"\bfunction\b.*?\bendfunction\b", "", src, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    regs = {}
    for names in DECL.findall(text):
        for name in re.split(r"\s*,\s*", names.strip()):
            # registers get non-blocking assignments; regs of always @* blocks do not
            if re.search(rf"\b{name}\s*(\[[^\]]*\])?\s*<=", text):
                regs[name] = len(nets[m]["netnames"][name]["bits"])
    declared[m] = regs
params = ", ".join(f"{k} = {int(v, 2)}" for k, v in
                   sorted(nets["ab_core"].get("parameter_default_values", {}).items()))

# transistor estimates of `stat -tech cmos`
transistors = {base(k): int(v) for k, v in re.findall(
    r"=== (.+?) ===.*?Estimated number of transistors:\s+(\d+)", cmos, re.S)}

rows, notes = [], []
for m in modules:
    by_type = stats[m]["num_cells_by_type"]
    ffs = sum(n for t, n in by_type.items() if "DFF" in t)
    logic = sum(n for t, n in by_type.items()                 # gates: not flip-flops, and not
                if t.startswith("$") and "DFF" not in t       # the parametrized submodules
                and not t.startswith("$paramod"))
    mod = nets[m]
    q_bits = {b for c in mod["cells"].values() if "DFF" in c["type"]
              for b in c["connections"]["Q"] if isinstance(b, int)}
    owners = {}                                    # flip-flop bit -> registers it drives
    for name, width in declared[m].items():
        bits = mod["netnames"].get(name, {}).get("bits", [])
        kept = [b for b in bits if b in q_bits]
        for b in kept:
            owners.setdefault(b, []).append(name)
        if len(kept) < width:
            notes.append(f"`{m}.{name}`: {width - len(kept)} of {width} bits removed "
                         "(never read, or constant)")
        elif len(kept) > width:
            notes.append(f"`{m}.{name}`: {width} bits declared, {len(kept)} flip-flops "
                         "(state re-encoded by the FSM pass)")
    shared = Counter(tuple(sorted(v)) for v in owners.values() if len(v) > 1)
    for regs, n in sorted(shared.items()):
        notes.append(f"`{m}`: {n} flip-flops shared by " + " and ".join(f"`{r}`" for r in regs)
                     + " (equal next-state logic, merged)")
    rows.append((m, sum(declared[m].values()), ffs, logic, transistors.get(m, 0)))

inv = re.search(r"\|\s*\*\*total\*\*\s*\|\s*\*\*(\d+)\*\*", inventory.read_text())
tot = [sum(r[i] for r in rows) for i in (1, 2, 3)]
lines = [
    "# synth_core: generic synthesis of the chip, `tt_um_orcunyilmaz06_approxbeat`",
    "",
    f"Generated by `flow/synth` ({version}) on {datetime.datetime.now():%Y-%m-%d %H:%M}. "
    f"Do not edit by hand. Parameters of `ab_core`: {params}.",
    "",
    "These are generic Yosys gates; there is no PDK yet. The flip-flop counts are exact. The "
    "logic-cell and transistor counts are technology-free estimates, not an area. The "
    "transistor estimate (`stat -tech cmos`) covers the logic gates and the plain "
    "flip-flops. Yosys' CMOS table has no entry for flip-flops with reset or enable, which "
    "are almost all of them. The same RTL always gives the same counts, but the logic count of "
    "an unchanged module moves by about 1 % when another module changes, so smaller "
    "differences between designs are noise.",
    "",
    "| Module | Declared register bits | Flip-flops after synthesis | Logic cells | Transistors, logic (est.) |",
    "|---|---:|---:|---:|---:|",
]
lines += [f"| `{m}` | {d} | {f} | {lg} | {t} |" for m, d, f, lg, t in rows]
lines += [f"| **total** | **{tot[0]}** | **{tot[1]}** | **{tot[2]}** | "
          f"**{transistors.get('design hierarchy', 0)}** |", ""]
if inv:
    det = sum(r[1] for r in rows if r[0] in core)
    lines += [f"`ab_state_inventory` counts {inv.group(1)} flip-flops "
              f"([state_inventory.md](state_inventory.md)). The declared bits of the detector, "
              f"`ab_core` and its submodules, are {det}. The Tiny Tapeout wrapper adds "
              f"{tot[0] - det}: the handshake and the held results.", ""]
lines += ["## Where synthesis differs from the declared registers", ""]
lines += [f"- {n}" for n in notes] or ["- nowhere"]
lines += [""]
report.write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {report}: {tot[1]} flip-flops after synthesis, {tot[0]} declared")
