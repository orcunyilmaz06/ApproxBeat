function ab_int_study()
%AB_INT_STUDY  Integer model against the float model: rounding, stability, word lengths.
%   Regenerates results/float_baseline.*, int_baseline.*, range_study.*,
%   state_inventory.md, wordlength_grid.csv and int_study.md (about 10 minutes):
%   1. float and integer baselines on all 48 records, and how many detections differ;
%   2. where and how to round: six rounding configurations of the integer model;
%   3. stability: the float model with +-1 LSB of input dither, five seeds;
%   4. word length of the stored squared derivative against accuracy and flip-flops:
%      truncation against rounding, then a grid of dropped LSBs x clipped MSBs.
P  = ab_paths();
p  = ab_params();
q  = {'save', false, 'verbose', false};
t0 = tic;
r228 = ab_load_record('228', p.fs);

% 1. baselines
F = ab_run_eval('model', @ab_pt_float, 'tag', 'float_baseline', 'verbose', false);
I = ab_run_eval('model', @ab_pt_int, 'tag', 'int_baseline', 'verbose', false);
nrec = height(F.table);
[same, near] = deal(0);
for k = 1:nrec
    a = F.detections{k}; b = I.detections{k};
    same = same + numel(intersect(a, b));
    near = near + ab_match_beats(a, b, 2).tp;           % within +-2 samples (10 ms)
end
n_f = sum(cellfun(@numel, F.detections));
n_i = sum(cellfun(@numel, I.detections));
changed = find(F.table.fn ~= I.table.fn | F.table.fp ~= I.table.fp);
fn228_float = F.table.fn(strcmp(F.table.record, '228'));

% 2. where and how to round (no saturation, to isolate rounding)
cfg = {'A: der >> 3, then square (Tompkins)',        5, 3, 0,  false
       'B: square, then >> 6, truncated',            5, 0, 6,  false
       'B: square, then >> 6, rounded (baseline)',   5, 0, 6,  true
       'C: B rounded, with 2 more low-pass bits',    3, 0, 10, true
       'D: no rounding in the chain, sq truncated',  0, 0, 16, false
       'D: no rounding in the chain, sq rounded',    0, 0, 16, true};
rnd = cell(size(cfg, 1), 1);
for k = 1:size(cfg, 1)
    pk = p; pk.sq_bits = inf;
    pk.lp_shift = cfg{k, 2}; pk.der_shift = cfg{k, 3}; pk.sq_shift = cfg{k, 4}; pk.sq_round = cfg{k, 5};
    rnd{k} = summary(ab_run_eval('model', @ab_pt_int, 'params', pk, q{:}), pk);
    rnd{k}.fn228_exact = fn_exact_decision(r228, pk);
end

% 3. stability under +-1 LSB input dither (float model)
seeds = 1:5;
dith = zeros(nrec, numel(seeds));
dg = zeros(numel(seeds), 3);
for k = seeds
    S = ab_run_eval('model', @(adu, pp) ab_pt_float(dither(adu, k, p.adc_bits), pp), q{:});
    dith(:, k) = S.table.fn + S.table.fp;
    dg(k, :) = [S.gross.se_pct(1), S.gross.ppv_pct(1), S.gross.der_pct(1)];
end
spread = max(dith, [], 2) - min(dith, [], 2);

% 4a. dropping LSBs of sq: truncation against rounding (no saturation)
R = ab_range_study();
sq_data_bits = R.bits_data_max(strcmp(R.signal, 'sq'));
trunc = zeros(0, 5);
for e = [0 2 4 6]
    row = e;
    for rnd_on = [false true]
        pk = p; pk.sq_bits = inf; pk.sq_shift = p.sq_shift + e; pk.sq_round = rnd_on;
        s = summary(ab_run_eval('model', @ab_pt_int, 'params', pk, q{:}), pk);
        row = [row, s.der, s.fn228]; %#ok<AGROW>
    end
    trunc(end+1, :) = row; %#ok<AGROW>
end

% 4b. grid: LSBs dropped x MSBs clipped, rounding on
G = table();
for e = 0:4
    for c = [0 2 4 6]
        pk = p; pk.sq_shift = p.sq_shift + e; pk.sq_bits = sq_data_bits - e - c;
        s = summary(ab_run_eval('model', @ab_pt_int, 'params', pk, q{:}), pk);
        G = [G; table(e, c, s.sq_bits, 30 * s.sq_bits, s.ff, s.se, s.ppv, s.der, s.fn228, ...
             'VariableNames', {'lsbs_dropped', 'msbs_clipped', 'sq_bits', 'mwi_line_bits', ...
                               'total_ff', 'se_pct', 'ppv_pct', 'der_pct', 'fn_228'})]; %#ok<AGROW>
    end
end
G.pareto = pareto(G.total_ff, G.der_pct);
writetable(G, fullfile(P.results, 'wordlength_grid.csv'));
inv = ab_inventory_report(p);
secs = toc(t0);

% report
fid = fopen(fullfile(P.results, 'int_study.md'), 'w', 'n', 'UTF-8');
closer = onCleanup(@() fclose(fid));
fprintf(fid, '# Integer model study\n\n');
fprintf(fid, ['Generated by `ab_int_study` on %s, MATLAB %s, %.0f s. Do not edit by hand. ' ...
              'Protocol: [docs/eval_protocol.md](../docs/eval_protocol.md). Baseline integer design: ' ...
              'lp_shift %d, der_shift %d, sq_shift %d, sq rounded = %d, sq saturated at %g bits, %d ' ...
              'flip-flops ([state_inventory.md](state_inventory.md)).\n\n'], ...
        char(datetime('now', 'Format', 'yyyy-MM-dd HH:mm')), version('-release'), secs, p.lp_shift, ...
        p.der_shift, p.sq_shift, p.sq_round, p.sq_bits, sum(inv.total));

fprintf(fid, '## 1. Integer baseline against the float model\n\n');
fprintf(fid, '| Model | Se (%%) | +P (%%) | F1 (%%) | DER (%%) |\n|---|---:|---:|---:|---:|\n');
fprintf(fid, '| float, `ab_pt_float` | %.2f | %.2f | %.2f | %.3f |\n', F.gross.se_pct(1), ...
        F.gross.ppv_pct(1), F.gross.f1_pct(1), F.gross.der_pct(1));
fprintf(fid, '| integer, `ab_pt_int` | %.2f | %.2f | %.2f | %.3f |\n\n', I.gross.se_pct(1), ...
        I.gross.ppv_pct(1), I.gross.f1_pct(1), I.gross.der_pct(1));
fprintf(fid, ['The float model makes %d detections and the integer model %d. %d (%.2f %%) of the ' ...
              'integer detections sit on exactly the same sample as a float detection, %d (%.2f %%) ' ...
              'within 10 ms.\n\n'], n_f, n_i, same, 100 * same / n_i, near, 100 * near / n_i);
if isempty(changed)
    fprintf(fid, 'No record differs in FN or FP.\n');
else
    fprintf(fid, 'Records whose FN or FP differ (float -> integer):\n\n| Record | FN | FP |\n|---|---|---|\n');
    for k = changed'
        fprintf(fid, '| %s | %d -> %d | %d -> %d |\n', F.table.record{k}, F.table.fn(k), I.table.fn(k), ...
                F.table.fp(k), I.table.fp(k));
    end
end

fprintf(fid, '\n## 2. Where and how to round\n\n');
fprintf(fid, ['Integer model with the same overall scaling and different rounding, without saturation. ' ...
              'The last column reruns record 228 with the same integer filter chain but exact ' ...
              'decision logic. Float model: %d FN in record 228.\n\n'], fn228_float);
fprintf(fid, '| Configuration | lp bits | der bits | sq bits | Se (%%) | +P (%%) | DER (%%) | FN in 228 | FN in 228, exact decision logic |\n');
fprintf(fid, '|---|---:|---:|---:|---:|---:|---:|---:|---:|\n');
for k = 1:numel(rnd)
    s = rnd{k};
    fprintf(fid, '| %s | %d | %d | %d | %.2f | %.2f | %.3f | %d | %d |\n', cfg{k, 1}, s.lp_bits, ...
            s.der_bits, s.sq_bits, s.se, s.ppv, s.der, s.fn228, s.fn228_exact);
end

fprintf(fid, '\n## 3. Stability under +/-1 LSB of input dither (float model, %d seeds)\n\n', numel(seeds));
fprintf(fid, ['Across seeds: Se %.2f-%.2f %%, +P %.2f-%.2f %%, DER %.3f-%.3f %% (undithered: Se %.2f, ' ...
              '+P %.2f, DER %.3f). Largest per-record change in FN+FP: %d (record %s).\n'], ...
        min(dg(:, 1)), max(dg(:, 1)), min(dg(:, 2)), max(dg(:, 2)), min(dg(:, 3)), max(dg(:, 3)), ...
        F.gross.se_pct(1), F.gross.ppv_pct(1), F.gross.der_pct(1), max(spread), ...
        F.table.record{find(spread == max(spread), 1)});

fprintf(fid, '\n## 4. Word length of the stored squared derivative\n\n');
fprintf(fid, ['`sq` feeds the 30-word MWI delay line and sets the width of the MWI and of most decision ' ...
              'registers. On MIT-BIH it needs %d bits at the baseline shift ([range_study.md](range_study.md)).\n\n'], ...
        sq_data_bits);
fprintf(fid, '### 4a. Dropping LSBs: truncation against rounding (no saturation)\n\n');
fprintf(fid, '| LSBs dropped | DER truncated (%%) | FN in 228 | DER rounded (%%) | FN in 228 |\n|---:|---:|---:|---:|---:|\n');
for k = 1:size(trunc, 1)
    fprintf(fid, '| %d | %.3f | %d | %.3f | %d |\n', trunc(k, :));
end
fprintf(fid, ['\n### 4b. LSBs dropped x MSBs clipped (rounding on)\n\nClipped MSBs saturate `sq` below its ' ...
              'MIT-BIH maximum. *Pareto* marks configurations that no other row beats on both ' ...
              'flip-flops and DER. Data: [wordlength_grid.csv](wordlength_grid.csv).\n\n']);
fprintf(fid, '| LSBs dropped | MSBs clipped | sq bits | Flip-flops | Se (%%) | +P (%%) | DER (%%) | FN in 228 | Pareto |\n');
fprintf(fid, '|---:|---:|---:|---:|---:|---:|---:|---:|---|\n');
for k = 1:height(G)
    mark = ''; if G.pareto(k), mark = 'yes'; end
    fprintf(fid, '| %d | %d | %d | %d | %.2f | %.2f | %.3f | %d | %s |\n', G.lsbs_dropped(k), ...
            G.msbs_clipped(k), G.sq_bits(k), G.total_ff(k), G.se_pct(k), G.ppv_pct(k), ...
            G.der_pct(k), G.fn_228(k), mark);
end
fprintf('wrote results/int_study.md (%.0f s)\n', secs);
end

function s = summary(S, p)
w = ab_int_widths(p);
s.se = S.gross.se_pct(1); s.ppv = S.gross.ppv_pct(1); s.der = S.gross.der_pct(1);
s.fn228 = S.table.fn(strcmp(S.table.record, '228'));
s.lp_bits = w.lp.bits; s.der_bits = w.der.bits; s.sq_bits = w.sq.bits;
s.ff = sum(ab_state_inventory(p).total);
end

function fn = fn_exact_decision(r, p)
% integer filter chain, exact decision logic, record r
p_int = p; p_int.arith = 'int';
s = ab_pt_filters([r.adu; repmat(r.adu(end), p.fs, 1)], p_int);
pf = p; pf.arith = 'float';
det = ab_pt_decide(s, pf);
fn = ab_match_beats(ab_reference_beats(r.ann, r.fs_orig), det.sample / p.fs, 0.15).fn;
end

function on = pareto(cost, err)
on = false(size(cost));
for k = 1:numel(cost)
    on(k) = ~any((cost <= cost(k) & err < err(k)) | (cost < cost(k) & err <= err(k)));
end
end

function adu = dither(adu, seed, bits)
rs = RandStream('mt19937ar', 'Seed', seed);
adu = min(max(adu + randi(rs, [-1 1], size(adu)), 0), 2^bits - 1);
end
