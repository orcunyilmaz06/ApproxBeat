function ab_wordlength_study()
%AB_WORDLENGTH_STUDY  Choose the word length of the stored squared derivative on DS1 (D19).
%   Candidates: e = 0..6 LSBs dropped (sq_shift = 6 + e) times c = 0..6 MSBs clipped
%   (sq saturated at 16 - e - c bits), rounding on, integer model. The exact design
%   (e = c = 0) is the reference. Every candidate's flip-flops come from
%   ab_state_inventory, which follows the word lengths into the MWI and the levels.
%   Selection rule, fixed before the run:
%     acceptable  on DS1: DER at most 0.02 pp above the reference, Se and +P each at most
%                 0.02 pp below it
%     chosen      the acceptable candidate with the fewest flip-flops; ties go to the
%                 lower DS1 DER, then to fewer clipped MSBs
%     confirmed   the chosen candidate also meets the same tolerance on DS2; only then
%                 is it adopted
%   Writes results/wordlength_study.md (about 10 minutes).
P   = ab_paths();
p0  = ab_params();
tol = 0.02;                                        % pp
q   = {'model', @ab_pt_int, 'save', false, 'verbose', false};
t0  = tic;
[E, C] = meshgrid(0:6, 0:6);
E = E(:); C = C(:);
nc = numel(E);
g  = zeros(nc, 10);                                % [Se +P DER] DS1, DS2, all 48; flip-flops
S  = cell(nc, 1);
for k = 1:nc
    p = cand_params(p0, E(k), C(k));
    S{k} = ab_run_eval('params', p, q{:});
    G = S{k}.gross;
    row = @(name) [G.se_pct(G.set == name), G.ppv_pct(G.set == name), G.der_pct(G.set == name)];
    g(k, :) = [row("DS1 (design set)"), row("DS2 (held-out set)"), row("all 48 records"), ...
               sum(ab_state_inventory(p).total)];
end
ref = find(E == 0 & C == 0);
ok  = meets(g(:, 1:3), g(ref, 1:3), tol);
cand = find(ok);
[~, o] = sortrows([g(cand, 10), g(cand, 3), C(cand)]);
chosen = cand(o(1));
confirmed = meets(g(chosen, 4:6), g(ref, 4:6), tol);
secs = toc(t0);

% report
fid = fopen(fullfile(P.results, 'wordlength_study.md'), 'w', 'n', 'UTF-8');
closer = onCleanup(@() fclose(fid));
fprintf(fid, '# Word length of the stored squared derivative: DS1 choice, DS2 check\n\n');
fprintf(fid, ['Generated by `ab_wordlength_study` on %s, MATLAB %s, %.0f s. Do not edit by hand. ' ...
              'Integer model, rounding on. Choice made on DS1 only, by the rule in the script ' ...
              'header; DS2 is held out. Protocol: [docs/eval_protocol.md](../docs/eval_protocol.md).\n\n'], ...
        char(datetime('now', 'Format', 'yyyy-MM-dd HH:mm')), version('-release'), secs);
fprintf(fid, ['**Rule.** Acceptable: on DS1, DER at most %.2f pp above the exact design, Se and +P ' ...
              'each at most %.2f pp below it. Chosen: the acceptable candidate with the fewest ' ...
              'flip-flops. Confirmed: the chosen candidate meets the same tolerance on DS2.\n\n'], tol, tol);
fprintf(fid, ['**Result.** Chosen: %d LSBs dropped, %d MSBs clipped, `sq` in %d bits, %d flip-flops ' ...
              '(exact design: %d). DS2: %s.\n\n'], E(chosen), C(chosen), sq_bits(E(chosen), C(chosen)), ...
        g(chosen, 10), g(ref, 10), verdict(confirmed));

fprintf(fid, '## 1. DS2 and all 48 records: exact design against the chosen one\n\n');
fprintf(fid, '| Design | Flip-flops | DS1 Se | DS1 +P | DS1 DER | DS2 Se | DS2 +P | DS2 DER | all 48 Se | all 48 +P | all 48 DER |\n');
fprintf(fid, '|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|\n');
for k = [ref, chosen]
    name = 'exact'; if k == chosen, name = sprintf('%d LSBs, %d MSBs (chosen)', E(k), C(k)); end
    fprintf(fid, '| %s | %d | %.2f | %.2f | %.3f | %.2f | %.2f | %.3f | %.2f | %.2f | %.3f |\n', ...
            name, g(k, 10), g(k, 1:9));
end
fprintf(fid, '\nAll values in %%.\n');

fprintf(fid, '\n## 2. Records whose FN or FP changed (all 48 records)\n\n');
B = S{ref}.table; X = S{chosen}.table;
d = find(B.fn ~= X.fn | B.fp ~= X.fp);
if isempty(d)
    fprintf(fid, 'None.\n');
else
    [~, ~, ds1, ds2] = ab_records();
    fprintf(fid, '| Record | Set | FN | FP |\n|---|---|---|---|\n');
    for k = d'
        set = 'paced';
        if ismember(B.record{k}, ds1), set = 'DS1'; end
        if ismember(B.record{k}, ds2), set = 'DS2'; end
        fprintf(fid, '| %s | %s | %d -> %d | %d -> %d |\n', B.record{k}, set, B.fn(k), X.fn(k), B.fp(k), X.fp(k));
    end
end

fprintf(fid, '\n## 3. Every candidate\n\n');
fprintf(fid, ['*Acceptable* applies the rule on DS1. DS2 and all-48 columns are reported, not used ' ...
              'for the choice.\n\n']);
fprintf(fid, '| LSBs dropped | MSBs clipped | sq bits | Flip-flops | DS1 Se | DS1 +P | DS1 DER | DS2 DER | all 48 DER | Acceptable |\n');
fprintf(fid, '|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|\n');
[~, o] = sortrows([E, C]);
for k = o'
    mark = ''; if ok(k), mark = 'yes'; end
    if k == chosen, mark = '**chosen**'; end
    fprintf(fid, '| %d | %d | %d | %d | %.2f | %.2f | %.3f | %.3f | %.3f | %s |\n', E(k), C(k), ...
            sq_bits(E(k), C(k)), g(k, 10), g(k, 1:3), g(k, 6), g(k, 9), mark);
end
fprintf('wrote results/wordlength_study.md (%.0f s): chosen %d LSBs, %d MSBs, %d flip-flops, DS2 %s\n', ...
        secs, E(chosen), C(chosen), g(chosen, 10), verdict(confirmed));
end

function p = cand_params(p, e, c)
p.sq_round = true;
p.sq_shift = 6 + e;
p.sq_bits  = sq_bits(e, c);
end

function b = sq_bits(e, c)
b = 16 - e - c;                                    % 16 bits hold the exact sq on MIT-BIH (D11)
end

function ok = meets(x, ref, tol)
% x, ref: [Se +P DER] rows
ok = x(:, 3) <= ref(3) + tol & x(:, 1) >= ref(1) - tol & x(:, 2) >= ref(2) - tol;
end

function s = verdict(confirmed)
if confirmed, s = 'confirmed'; else, s = 'not confirmed'; end
end
