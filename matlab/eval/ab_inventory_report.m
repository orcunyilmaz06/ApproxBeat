function T = ab_inventory_report(p)
%AB_INVENTORY_REPORT  Write the register inventory of the integer design to results/.
%   T = AB_INVENTORY_REPORT() lists every register of the baseline integer
%   detector (ab_state_inventory) with its word length and writes
%   results/state_inventory.md. T = AB_INVENTORY_REPORT(p) uses parameter set p.
if nargin < 1, p = ab_params(); end
T = ab_state_inventory(p);
P = ab_paths();
fid = fopen(fullfile(P.results, 'state_inventory.md'), 'w', 'n', 'UTF-8');
closer = onCleanup(@() fclose(fid));
fprintf(fid, '# Register inventory of the integer detector\n\n');
fprintf(fid, ['Generated by `ab_inventory_report` on %s from `ab_state_inventory` and the word ' ...
              'lengths of `ab_int_widths`. Do not edit by hand. Combinational logic (adders, ' ...
              'comparators, the squarer) is not counted.\n\n'], ...
        char(datetime('now', 'Format', 'yyyy-MM-dd HH:mm')));
fprintf(fid, '| Block | Register | Words | Bits | Flip-flops |\n|---|---|---:|---:|---:|\n');
for k = 1:height(T)
    fprintf(fid, '| %s | %s | %d | %d | %d |\n', T.block{k}, T.register{k}, T.words(k), ...
            T.bits(k), T.total(k));
end
blocks = unique(T.block, 'stable');
fprintf(fid, '\n| Block | Flip-flops | Share |\n|---|---:|---:|\n');
for k = 1:numel(blocks)
    b = sum(T.total(strcmp(T.block, blocks{k})));
    fprintf(fid, '| %s | %d | %.0f %% |\n', blocks{k}, b, 100 * b / sum(T.total));
end
fprintf(fid, '| **total** | **%d** | |\n', sum(T.total));
delay = contains(T.register, 'delay line');
fprintf(fid, ['\nThe four delay lines hold %d of the %d flip-flops (%.0f %%). Parameters: lp_shift = %d, ' ...
              'der_shift = %d, sq_shift = %d, sq_bits = %g, age_bits = %d.\n'], sum(T.total(delay)), ...
        sum(T.total), 100 * sum(T.total(delay)) / sum(T.total), p.lp_shift, p.der_shift, ...
        p.sq_shift, p.sq_bits, p.age_bits);
end
