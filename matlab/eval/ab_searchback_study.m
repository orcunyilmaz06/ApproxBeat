function ab_searchback_study()
%AB_SEARCHBACK_STUDY  Choose the SPKI outlier clip on DS1, report it on DS2 (D14).
%   Candidates: no clip (the baseline), and a QRS peak clipped to 2, 1.5 or 1.25 x SPKI
%   before it updates SPKI. Selection rule, fixed before the run: the lowest DER on DS1;
%   candidates within 0.01 pp of it count as tied, and among tied ones the weakest clip
%   wins. Every candidate is then put through the robustness test: the six rounding
%   configurations of ab_int_study, and the spread of record 228 and of the gross DER
%   across them. Writes results/searchback_study.md (about 6 minutes).
P  = ab_paths();
p0 = ab_params();
p0.spk_clip_shifts = [];
q  = {'save', false, 'verbose', false};
t0 = tic;
cand = {'none (baseline)', []
        '2 x SPKI',        [0 0]
        '1.5 x SPKI',      [0 1]
        '1.25 x SPKI',     [0 2]};
nc = size(cand, 1);

% 1. float model, every candidate
S = cell(nc, 1);
g = zeros(nc, 10);                  % [Se +P DER] for DS1, DS2, all 48; FN in 228
for k = 1:nc
    p = p0; p.spk_clip_shifts = cand{k, 2};
    S{k} = ab_run_eval('model', @ab_pt_float, 'params', p, q{:});
    G = S{k}.gross;
    row = @(name) [G.se_pct(G.set == name), G.ppv_pct(G.set == name), G.der_pct(G.set == name)];
    g(k, :) = [row("DS1 (design set)"), row("DS2 (held-out set)"), row("all 48 records"), ...
               S{k}.table.fn(strcmp(S{k}.table.record, '228'))];
end
best = min(g(:, 3));
chosen = find(g(:, 3) <= best + 0.01, 1);          % candidates run from weakest clip up

% 2. robustness: rounding configurations of the integer model
cfg = {5, 3, 0, false; 5, 0, 6, false; 5, 0, 6, true; 3, 0, 10, true; 0, 0, 16, false; 0, 0, 16, true};
rob = zeros(nc, size(cfg, 1), 2);                  % (candidate, config, [FN 228, DER])
for k = 1:nc
    for c = 1:size(cfg, 1)
        p = p0; p.spk_clip_shifts = cand{k, 2}; p.sq_bits = inf;
        [p.lp_shift, p.der_shift, p.sq_shift, p.sq_round] = cfg{c, :};
        R = ab_run_eval('model', @ab_pt_int, 'params', p, q{:});
        rob(k, c, :) = [R.table.fn(strcmp(R.table.record, '228')), R.gross.der_pct(1)];
    end
end
secs = toc(t0);

% report
fid = fopen(fullfile(P.results, 'searchback_study.md'), 'w', 'n', 'UTF-8');
closer = onCleanup(@() fclose(fid));
fprintf(fid, '# Searchback robustness: outlier-clipped signal level\n\n');
fprintf(fid, ['Generated by `ab_searchback_study` on %s, MATLAB %s, %.0f s. Do not edit by hand. ' ...
              'Choice made on DS1 only, by the rule in the script header; DS2 is held out.\n\n'], ...
        char(datetime('now', 'Format', 'yyyy-MM-dd HH:mm')), version('-release'), secs);
fprintf(fid, '## 1. Candidates (float model)\n\n');
fprintf(fid, ['| SPKI update clipped at | DS1 Se | DS1 +P | DS1 DER | DS2 Se | DS2 +P | DS2 DER | ' ...
              'all 48 Se | all 48 +P | all 48 DER | FN in 228 |\n|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|\n']);
for k = 1:nc
    mark = ''; if k == chosen, mark = ' **(chosen)**'; end
    fprintf(fid, '| %s%s | %.2f | %.2f | %.3f | %.2f | %.2f | %.3f | %.2f | %.2f | %.3f | %d |\n', ...
            cand{k, 1}, mark, g(k, :));
end
fprintf(fid, '\nAll values in %%, except FN. Record 228 belongs to DS2.\n');

fprintf(fid, '\n## 2. Records that change with the chosen clip (float model, all 48 records)\n\n');
B = S{1}.table; C = S{chosen}.table;
d = find(B.fn ~= C.fn | B.fp ~= C.fp);
if isempty(d) || chosen == 1
    fprintf(fid, 'None: the baseline was kept.\n');
else
    fprintf(fid, '| Record | Set | FN | FP |\n|---|---|---|---|\n');
    for k = d'
        set = 'paced';
        if ismember(B.record{k}, ab_records_ds(1)), set = 'DS1'; end
        if ismember(B.record{k}, ab_records_ds(2)), set = 'DS2'; end
        fprintf(fid, '| %s | %s | %d -> %d | %d -> %d |\n', B.record{k}, set, B.fn(k), C.fn(k), B.fp(k), C.fp(k));
    end
end

fprintf(fid, '\n## 3. Robustness to rounding (integer model, six configurations of `int_study.md` section 2)\n\n');
fprintf(fid, ['A robust detector gives nearly the same result whichever rounding is used. Spread = max - min ' ...
              'across the six configurations.\n\n| SPKI update clipped at | FN in 228 | Spread | DER all 48 (%%) | Spread (pp) |\n' ...
              '|---|---|---:|---|---:|\n']);
for k = 1:nc
    f = rob(k, :, 1); e = rob(k, :, 2);
    fprintf(fid, '| %s | %d-%d | %d | %.3f-%.3f | %.3f |\n', cand{k, 1}, min(f), max(f), max(f) - min(f), ...
            min(e), max(e), max(e) - min(e));
end
fprintf('wrote results/searchback_study.md (%.0f s), chosen: %s\n', secs, cand{chosen, 1});
end

function r = ab_records_ds(which)
[~, ~, ds1, ds2] = ab_records();
if which == 1, r = ds1; else, r = ds2; end
end
