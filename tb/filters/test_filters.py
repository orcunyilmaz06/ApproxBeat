"""Bit-exact check of rtl/ab_filters.v against the integer model's golden vectors.

Every input sample is driven for one clock cycle; while it is applied, the stage values
of that sample (lp_n, hp_n, der_n, sq_n, mwi_n) must equal its row of <stream>_samples.npy.
The first difference fails the test. Format: docs/golden_vectors.md.

  smoke_vectors  the committed set in tb/vectors (always runs)
  full_records   all 48 records in data/golden, if AB_FULL=1 (AB_RECORDS=100,228 for a
                 subset); a complete run writes results/rtl_filters.md
"""
import datetime
import json
import os
from pathlib import Path

import cocotb
import numpy as np
from cocotb.clock import Clock
from cocotb.triggers import ClockCycles, FallingEdge, ReadOnly

from ab_tb import merge_shards, shard

REPO = Path(__file__).resolve().parents[2]
SMOKE = REPO / "tb" / "vectors"
GOLDEN = REPO / "data" / "golden"
SIGNALS = (("lp_n", True), ("hp_n", True), ("der_n", True), ("sq_n", False), ("mwi_n", False))


async def reset(dut):
    dut.in_valid.value = 0
    dut.in_adu.value = 0
    dut.rst_n.value = 0
    await ClockCycles(dut.clk, 2)
    await FallingEdge(dut.clk)
    dut.rst_n.value = 1


async def check_stream(dut, path):
    golden = np.load(path)
    await reset(dut)
    for n, row in enumerate(golden.tolist()):
        await FallingEdge(dut.clk)
        dut.in_adu.value = row[0]
        dut.in_valid.value = 1
        await ReadOnly()
        for col, (name, signed) in enumerate(SIGNALS, start=1):
            value = getattr(dut, name).value
            got = value.to_signed() if signed else value.to_unsigned()
            if got != row[col]:
                raise AssertionError(
                    f"{path.name}: sample {n} (adu {row[0]}): {name} = {got}, golden {row[col]}")
    await FallingEdge(dut.clk)
    dut.in_valid.value = 0
    dut._log.info("%s: %d samples bit-exact", path.name, len(golden))
    return len(golden)


@cocotb.test()
async def smoke_vectors(dut):
    cocotb.start_soon(Clock(dut.clk, 10, "ns").start())
    paths = sorted(SMOKE.glob("*_samples.npy"))
    assert paths, f"no smoke vectors in {SMOKE}"
    total = 0
    for path in paths:
        total += await check_stream(dut, path)
    dut._log.info("smoke set: %d streams, %d samples bit-exact", len(paths), total)


@cocotb.test(skip=os.environ.get("AB_FULL") != "1")
async def full_records(dut):
    cocotb.start_soon(Clock(dut.clk, 10, "ns").start())
    wanted = [r for r in os.environ.get("AB_RECORDS", "").split(",") if r]
    paths = sorted(GOLDEN.glob("*_samples.npy"))
    if wanted:
        paths = [p for p in paths if p.name.split("_")[0] in wanted]
    paths = shard(paths)
    assert paths, f"no golden vectors in {GOLDEN}: run ab_write_golden in MATLAB"
    counts = {}
    for path in paths:
        counts[path.name.split("_")[0]] = await check_stream(dut, path)
    dut._log.info("full set: %d records, %d samples bit-exact", len(paths), sum(counts.values()))
    if not wanted:
        write_report(counts)


def write_report(counts):
    counts = merge_shards(counts)
    if counts is None:
        return
    manifest = json.loads((GOLDEN / "manifest.json").read_text())
    lines = [
        "# rtl_filters: RTL filter chain against the golden vectors",
        "",
        f"Generated by `tb/filters` (cocotb test `full_records`) on "
        f"{datetime.datetime.now():%Y-%m-%d %H:%M}, {cocotb.SIM_NAME} {cocotb.SIM_VERSION}, "
        f"cocotb {cocotb.__version__}. Do not edit by hand.",
        "",
        f"Every sample of every record: `lp`, `hp`, `der`, `sq` and `mwi` of `rtl/ab_filters.v` "
        f"equal the golden vectors of the integer model (model commit "
        f"{manifest.get('git_commit', 'unknown')}, `data/golden/manifest.json`).",
        "",
        "| Record | Samples | Result |",
        "|---|---:|---|",
    ]
    lines += [f"| {rec} | {n} | bit-exact |" for rec, n in counts.items()]
    lines += [f"| **{len(counts)} records** | **{sum(counts.values())}** | **bit-exact** |", ""]
    (REPO / "results" / "rtl_filters.md").write_text("\n".join(lines), encoding="utf-8")
