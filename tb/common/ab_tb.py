"""Shared helpers for the ApproxBeat cocotb testbenches (docs/golden_vectors.md)."""
import datetime
import json
import os
from pathlib import Path

import cocotb
from cocotb.triggers import ReadOnly, RisingEdge

REPO = Path(__file__).resolve().parents[2]
SMOKE = REPO / "tb" / "vectors"
GOLDEN = REPO / "data" / "golden"


def u(handle):
    return int(handle.value)                   # unsigned; works for 1-bit Logic and LogicArray


def stems(full):
    """Stream stems (path without _samples.npy): the smoke set, or the 48 records of data/golden."""
    where = GOLDEN if full else SMOKE
    found = sorted(str(p)[:-len("_samples.npy")] for p in where.glob("*_samples.npy"))
    wanted = [r for r in os.environ.get("AB_RECORDS", "").split(",") if r] if full else []
    if wanted:
        found = [s for s in found if Path(s).name in wanted]
    assert found, f"no golden vectors in {where}" + (": run ab_write_golden in MATLAB" if full else "")
    return found, bool(wanted)


class EventChecker:
    """Compares the decision events of one stream with its golden peak and beat tables.

    events: the module with the event outputs; levels: ab_decide (for SPKI, NPKI, THR1,
    RR limit and the classified peak). Golden class 4 (a noise peak later taken by
    searchback) is class 2 when it is classified.
    """

    def __init__(self, events, levels, name, peaks, beats):
        self.ev, self.lv, self.name = events, levels, name
        self.peaks, self.beats = peaks.tolist(), beats.tolist()
        self.n = -1                            # sample being processed, set by the driver
        self.ip = self.ib = 0
        self.error = None
        self.tasks = []

    def start(self):
        self.tasks = [cocotb.start_soon(self._peaks()), cocotb.start_soon(self._beats())]

    def stop(self):
        for t in self.tasks:
            t.cancel()

    def fail(self, msg):
        if self.error is None:
            self.error = f"{self.name}: sample {self.n}: {msg}"

    def finish(self):
        assert self.error is None, self.error
        assert (self.ip, self.ib) == (len(self.peaks), len(self.beats)), \
            f"{self.name}: saw {self.ip}/{len(self.peaks)} peaks and {self.ib}/{len(self.beats)} beats"

    async def _peaks(self):
        ev, lv = self.ev, self.lv
        while True:
            await RisingEdge(ev.peak_valid)
            await ReadOnly()
            if self.ip == len(self.peaks):
                self.fail("peak event beyond the golden table")
                continue
            r = self.peaks[self.ip]            # index, value, class, thr1_used, n, age, spk, npk, thr1
            exp = (r[4], r[1], 2 if r[2] == 4 else r[2], r[5], r[6], r[7], r[8])
            got = (self.n, u(lv.c_val), u(ev.peak_class), u(lv.c_age), u(lv.spk), u(lv.npk), u(lv.thr1))
            if got != exp:
                self.fail(f"peak {self.ip}: (n, value, class, age, spk, npk, thr1) = {got}, golden {exp}")
            self.ip += 1

    async def _beats(self):
        ev, lv = self.ev, self.lv
        while True:
            await RisingEdge(ev.beat_valid)
            await ReadOnly()
            if self.ib == len(self.beats):
                self.fail("beat event beyond the golden table")
                continue
            r = self.beats[self.ib]            # n, r_age, kind, spk, npk, thr1, rr_lim
            exp = (r[0], r[1], r[2] - 1, r[3], r[4], r[5], r[6])
            got = (self.n, u(ev.beat_r_age), u(ev.beat_kind), u(lv.spk), u(lv.npk), u(lv.thr1), u(lv.rr_lim))
            if got != exp:
                self.fail(f"beat {self.ib}: (n, r_age, kind, spk, npk, thr1, rr_lim) = {got}, golden {exp}")
            self.ib += 1


def write_report(file, title, what, counts):
    """results/<file>: one row per record (samples, peaks, beats), all bit-exact."""
    manifest = json.loads((GOLDEN / "manifest.json").read_text())
    tot = [sum(c[i] for c in counts.values()) for i in range(3)]
    lines = [
        f"# {Path(file).stem}: {title}",
        "",
        f"Generated by cocotb test `full_records` on {datetime.datetime.now():%Y-%m-%d %H:%M}, "
        f"{cocotb.SIM_NAME} {cocotb.SIM_VERSION}, cocotb {cocotb.__version__}. Do not edit by hand.",
        "",
        f"{what} Golden vectors: integer model at commit {manifest.get('git_commit', 'unknown')} "
        "(`data/golden/manifest.json`).",
        "",
        "| Record | Samples | Peaks | Beats | Result |",
        "|---|---:|---:|---:|---|",
    ]
    lines += [f"| {r} | {s} | {p} | {b} | bit-exact |" for r, (s, p, b) in counts.items()]
    lines += [f"| **{len(counts)} records** | **{tot[0]}** | **{tot[1]}** | **{tot[2]}** | **bit-exact** |", ""]
    (REPO / "results" / file).write_text("\n".join(lines), encoding="utf-8")
