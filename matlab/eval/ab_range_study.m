function R = ab_range_study(p)
%AB_RANGE_STUDY  Dynamic range of every integer datapath signal on MIT-BIH.
%   R = AB_RANGE_STUDY() runs the integer filter chain (ab_params, arith = 'int',
%   no saturation) over all 48 records and compares, for each signal, the analytic
%   worst-case word length (ab_int_widths) with the largest value seen and with the
%   word length that covers all but one sample in a million. The gap is what
%   saturation can save. Writes results/range_study.{csv,md}.
%   R = AB_RANGE_STUDY(p) uses parameter set p.
if nargin < 1, p = ab_params(); p.sq_bits = inf; end
p.arith = 'int';
names = {'x', 'lp_acc', 'lp', 'hp_acc', 'hp', 'der_acc', 'der', 'sq', 'mwi'};
w = ab_int_widths(p);
recs = ab_records();
nb = 48;
H = zeros(numel(names), nb);                 % H(i, b): samples of signal i that need b bits
vmax = zeros(numel(names), 1);
vmin = zeros(numel(names), 1);
for k = 1:numel(recs)
    r = ab_load_record(recs{k}, p.fs);
    s = ab_pt_filters(r.adu, p);
    for i = 1:numel(names)
        v = s.(names{i});
        vmax(i) = max(vmax(i), max(v));
        vmin(i) = min(vmin(i), min(v));
        H(i, :) = H(i, :) + histcounts(bits_needed(v, w.(names{i}).signed), 0.5:1:nb + 0.5);
    end
end

[analytic, data_max, cover] = deal(zeros(numel(names), 1));
for i = 1:numel(names)
    analytic(i) = w.(names{i}).bits;
    data_max(i) = find(H(i, :), 1, 'last');
    c = cumsum(H(i, :)) / sum(H(i, :));
    cover(i) = find(c >= 1 - 1e-6, 1);
end
R = table(names(:), vmin, vmax, analytic, data_max, cover, ...
          'VariableNames', {'signal', 'min', 'max', 'bits_analytic', 'bits_data_max', 'bits_1e6'});

P = ab_paths();
writetable(R, fullfile(P.results, 'range_study.csv'));
fid = fopen(fullfile(P.results, 'range_study.md'), 'w', 'n', 'UTF-8');
closer = onCleanup(@() fclose(fid));
fprintf(fid, '# Dynamic range of the integer datapath\n\n');
fprintf(fid, ['Generated by `ab_range_study` on %s over all 48 MIT-BIH records (%d samples per signal). ' ...
              'Do not edit by hand.\n\n'], char(datetime('now', 'Format', 'yyyy-MM-dd HH:mm')), sum(H(1, :)));
fprintf(fid, ['*Analytic* bounds any input in the ADC range, so a register that wide can never overflow. ' ...
              '*Data max* is the widest value seen on MIT-BIH. *1e-6* covers all but one sample in a ' ...
              'million, so saturating there would clip about %d samples in the whole database.\n\n'], ...
        round(1e-6 * sum(H(1, :))));
fprintf(fid, '| Signal | Min | Max | Analytic bits | Data max bits | 1e-6 bits |\n|---|---:|---:|---:|---:|---:|\n');
for i = 1:height(R)
    fprintf(fid, '| %s | %d | %d | %d | %d | %d |\n', R.signal{i}, R.min(i), R.max(i), ...
            R.bits_analytic(i), R.bits_data_max(i), R.bits_1e6(i));
end
fprintf(fid, '\nSigned two''s complement except `sq` and `mwi` (unsigned). Parameters: der_shift = %d, sq_shift = %d.\n', ...
        p.der_shift, p.sq_shift);
end

function b = bits_needed(v, is_signed)
b = ones(size(v));
if is_signed
    pos = v >= 1;  b(pos) = floor(log2(v(pos))) + 2;
    neg = v <= -1; b(neg) = ceil(log2(-v(neg))) + 1;
else
    pos = v >= 1;  b(pos) = floor(log2(v(pos))) + 1;
end
end
